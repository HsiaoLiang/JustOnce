export type SeedStatus = "REQUESTED" | "ACCEPTED" | "ACTIVE" | "COMPLETED" | "DECLINED" | "CANCELLED";

export interface SeedReview {
  rating: number;
  comment: string;
}

export interface SeedBooking {
  listing: string;
  renter: string;
  start: number;
  end: number;
  status: SeedStatus;
  message?: string;
  /** Day offset the request was sent on (defaults to a week before pickup, never in the future). */
  requestedOn?: number;
  renterReview?: SeedReview;
  ownerReview?: SeedReview;
  /** For ACCEPTED/ACTIVE bookings: which sides have already done their check. */
  pickupDone?: ("OWNER" | "RENTER")[];
  returnDone?: ("OWNER" | "RENTER")[];
  /** Photos both sides took at pickup, when they shouldn't be the listing photos (for the AI photo comparison demo). */
  pickupPhotos?: string[];
  /** The renter's return photos, when they should differ from the pickup ones (for the AI photo comparison demo). */
  renterReturnPhotos?: string[];
  declineReason?: string;
  /** Delivered instead of meeting in person. */
  handover?: { method: "COURIER"; area: string; address: string } | { method: "LOCKER"; lockerId: string };
  /** A deposit claim after the owner flagged a problem at the return check. */
  claim?: {
    /** Pounds. */
    amount: number;
    reason: "DAMAGED" | "MISSING_PARTS" | "NOT_CLEANED" | "RETURNED_LATE";
    returnIssue: string;
    ownerNote: string;
    status: "OPEN" | "ACCEPTED";
  };
}

